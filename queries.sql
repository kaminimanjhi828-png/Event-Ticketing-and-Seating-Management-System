-- Query 1: Ticket booking details

SELECT 
    u.full_name,
    e.event_name,
    s.seat_number,
    t.price,
    t.status
FROM TICKET t
JOIN USERS u ON t.user_id = u.user_id
JOIN EVENT e ON t.event_id = e.event_id
JOIN SEAT s ON t.seat_id = s.seat_id;


-- Query 2: Available seats for an event

SELECT 
    s.seat_id,
    s.seat_number,
    sc.category_name
FROM EVENT e
JOIN SEAT s ON s.venue_id = e.venue_id
JOIN SEAT_CATEGORY sc ON s.category_id = sc.category_id
WHERE e.event_id = 1
  AND s.seat_id NOT IN (
      SELECT seat_id
      FROM TICKET
      WHERE event_id = 1
        AND status <> 'Cancelled'
  );


-- Query 3: Total revenue generated by each event

SELECT 
    e.event_name,
    SUM(p.amount) AS total_revenue
FROM PAYMENT p
JOIN TICKET t ON p.ticket_id = t.ticket_id
JOIN EVENT e ON t.event_id = e.event_id
WHERE p.payment_status = 'Success'
GROUP BY e.event_name;


-- Query 4: Refund details

SELECT 
    u.full_name,
    r.refund_amount,
    r.refund_status,
    r.reason
FROM REFUND r
JOIN PAYMENT p ON r.payment_id = p.payment_id
JOIN TICKET t ON p.ticket_id = t.ticket_id
JOIN USERS u ON t.user_id = u.user_id;


-- Query 5: Ticket scan log

SELECT 
    sl.scan_time,
    sl.scan_status,
    staff.full_name AS scanned_by
FROM SCAN_LOG sl
JOIN USERS staff ON sl.scanned_by = staff.user_id
WHERE sl.ticket_id = 1;


